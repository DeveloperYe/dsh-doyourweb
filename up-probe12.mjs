import { chromium } from "playwright-core";
import { readFileSync } from "fs";
const base = "http://172.16.0.59:3080";
const tok = readFileSync("D:/Users/Administrator/Documents/deepseek-harness/work/dsh-token.txt", "utf8").trim().replace("127.0.0.1", "172.16.0.59");
const ctx = await chromium.launch({ executablePath: process.env.CHROME_EXE, headless: true, args: ["--no-sandbox","--disable-gpu"] });
const page = await (await ctx.newContext()).newPage();
await page.goto(tok, { waitUntil: "domcontentloaded" });
await page.waitForSelector('[aria-label="添加文件或调用指令"]', { timeout: 45000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.click('[aria-label="添加文件或调用指令"]');
await page.waitForTimeout(900);
await page.evaluate(() => { const items = [...document.querySelectorAll('[role=menuitem],[role=menu] button,[class*=menu] button,[class*=Menu] button')]; const f = items.find(b => /文件file/.test((b.textContent||""))); if (f) f.click(); });
await page.waitForTimeout(2500);
const state = await page.evaluate(() => ({ dialog: [...document.querySelectorAll('[role=dialog]')].length, treeLike: [...document.querySelectorAll('[class*=tree],[class*=Tree],[class*=browse],[class*=Browse]')].length, fileInputs: document.querySelectorAll('input[type=file]').length, host: location.hostname }));
console.log("内网点文件后:", JSON.stringify(state));
await ctx.close();
